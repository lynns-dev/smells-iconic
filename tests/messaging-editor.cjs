const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const source = fs.readFileSync(path.join(__dirname, '../components/MessagingWorkspace.jsx'), 'utf8');
const start = source.indexOf('const escape =');
const end = source.indexOf('export function EmailMessageEditor', start);
const context = vm.createContext({});
vm.runInContext(source.slice(start, end).replace('export function ', 'function ') + '\nglobalThis.build = buildSimpleEmail;', context);
const build = context.build;
const body = build('Hello & welcome\n\nOne more thing.\nA second line.', 'Shop now', 'https://example.test/shop?a=1&b=2');
assert.match(body, /Hello &amp; welcome/);
assert.match(body, /One more thing\.<br>A second line\./);
assert.match(body, /href="https:\/\/example.test\/shop\?a=1&amp;b=2"/);
const hostile = build('<img src=x onerror=alert(1)>', '"><script>alert(1)</script>', 'https://example.test/" onclick="evil');
assert.ok(!hostile.includes('<img'));
assert.ok(!hostile.includes('<script>'));
assert.ok(hostile.includes('&quot; onclick=&quot;evil'));
assert.throws(() => build('hello', 'Open', 'javascript:alert(1)'));
assert.throws(() => build('hello', 'Open', '//example.test'));
assert.ok(!build('Just a message').includes('<a '));
console.log('Messaging email editor: safe text, paragraphs, CTA escaping and allowed link protocols passed.');
